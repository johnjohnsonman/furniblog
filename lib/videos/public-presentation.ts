export function presentVideo<T extends {youtube_id?: string | null; title?: string | null; channel_title?: string | null; thumbnail_url?: string | null}>(video: T): T {
  const translated = translations[video.youtube_id || ""]
  if (translated) return {...video, ...translated}
  const needsEnglish = (value?: string | null) => /[\uac00-\ud7af\u3130-\u318f\u3040-\u30ff\u4e00-\u9fff\u0400-\u04ff\u1ea0-\u1ef9]/.test(value || "")
  return {...video, title: needsEnglish(video.title) ? "Chair video (original-language source)" : video.title, channel_title: needsEnglish(video.channel_title) ? "Source channel on YouTube" : video.channel_title}
}
