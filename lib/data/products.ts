function affiliateLinks(
  links: Partial<Record<AffiliateChannel, string>> & { official: string }
): AffiliateLink[] {
  return (Object.entries(links) as [AffiliateChannel, string][]).map(
    ([channel, url]) => ({
      channel,
      label: AFFILIATE_LABELS[channel],
      url,
    })
  )
}

