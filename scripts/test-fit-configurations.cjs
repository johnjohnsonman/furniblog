const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
const root = path.resolve(__dirname,'..');
async function main() {
  const db = new PGlite();
  const schema = fs.readFileSync(path.join(root,'lib/supabase/migrations/054_product_fit_configurations.sql'),'utf8');
  const seed = fs.readFileSync(path.join(root,'lib/supabase/migrations/055_seed_fit_configurations_draft.sql'),'utf8');
  await db.exec(`create role anon; create role authenticated; create role service_role;
    create table products(id uuid primary key default gen_random_uuid(),slug text unique,published boolean default true,chair_specs jsonb default '{"preserved":true}');
    grant select on products to anon,authenticated;
    insert into products(slug) values('haworth-soji'),('haworth-very-task'),('haworth-zody-ii');`);
  await db.exec(schema); await db.exec(schema);
  await db.exec(seed); await db.exec(seed);
  assert.equal((await db.query('select count(*)::int as n from product_fit_configurations')).rows[0].n,7);
  assert.ok((await db.query('select chair_specs from products')).rows.every(r=>r.chair_specs.preserved));
  const very = (await db.query("select weight_capacity from product_fit_configurations where configuration_key in ('with-forward-tilt','without-forward-tilt') order by weight_capacity")).rows;
  assert.deepEqual(very.map(r=>Number(r.weight_capacity)),[147.4,158.8]);
  assert.equal((await db.query("select count(*)::int as n from product_fit_configurations where configuration_key like '%lumbar' and weight_capacity is null")).rows[0].n,4);
  await db.exec('set role anon');
  assert.equal((await db.query('select * from product_fit_configurations')).rows.length,0,'drafts hidden');
  await assert.rejects(db.exec("update product_fit_configurations set status='verified'"),/permission denied/);
  await db.exec('reset role');
  const activation = fs.readFileSync(path.join(root,'lib/supabase/migrations/056_activate_reviewed_us_fit_configurations.sql'),'utf8');
  await db.exec(activation); await db.exec(activation);
  assert.equal((await db.query("select count(*)::int as n from product_fit_configurations where status='verified'")).rows[0].n,3);
  await db.exec('set role anon');
  assert.equal((await db.query('select * from product_fit_configurations')).rows.length,3,'only reviewed configurations public');
  await db.exec('reset role');
  await db.exec(seed);
  await db.exec("update product_fit_configurations set weight_capacity=140 where configuration_key='with-forward-tilt'");
  await assert.rejects(db.exec(activation),/Reviewed configuration missing or changed/);
  await db.exec('rollback');
  assert.equal((await db.query("select count(*)::int as n from product_fit_configurations where status='verified'")).rows[0].n,0,'activation fails atomically on changed values');
  await db.exec(seed);
  await db.exec("update product_fit_configurations set status='verified'");
  await db.exec("update products set published=false where slug='haworth-zody-ii'");
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from product_fit_configurations')).rows.length,3,'unpublished products hidden');
  await db.exec('reset role');
  await assert.rejects(db.exec('update product_fit_configurations set seat_height_min=100,seat_height_max=20'),/check constraint/);
  await assert.rejects(db.exec('update product_fit_configurations set seat_depth_fixed=45'),/check constraint/);
  await assert.rejects(db.exec('update product_fit_configurations set seat_height_min=null'),/check constraint/);
  await db.exec(seed);
  assert.equal((await db.query("select count(*)::int as n from product_fit_configurations where status='draft'")).rows[0].n,7,'revisions must return to draft');
  await db.exec("delete from products where slug='haworth-zody-ii'; update product_fit_configurations set label='preserve-before-failure'");
  await assert.rejects(db.exec(seed),/Missing product/);
  await db.exec('rollback');
  assert.ok((await db.query('select label from product_fit_configurations')).rows.every(r=>r.label==='preserve-before-failure'),'atomic seed rollback');
  await db.close();
  console.log('PASS: 7 configurations; schema/seed reruns, independent capacities, unknowns, unchanged products, public RLS, write protection, range constraints, draft reset and atomic rollback');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
