const assert = require('node:assert/strict');
const { load } = require('cheerio');
const { comparisonPatch, guidePatch, comparisonSlug, faq } = require('./repair-contessa-aeron-buying.cjs');
const row = { content_html: '<h2>Old claims</h2><p>$2,040; 4D; 198 cm; 3.8 / 5</p><img src="a.jpg" alt="A"><img src="b.jpg" alt="B">' };
const revised = comparisonPatch(row);
const $ = load(revised.content_html);
assert.deepEqual($('img').map((_, el) => $(el).attr('src')).get(), ['a.jpg', 'b.jpg']);
assert.equal($('table caption').length, 1);
assert.equal($('h1').length, 0);
assert.equal($('a[href^="https://"]').length, 3);
assert.doesNotMatch($.text() + JSON.stringify(revised.faq), /\$2,040|\$1,521|\$519|4D|198 cm|3\.8 \/ 5|blood circulation|10-year/);
assert.match($.text(), /not a hands-on test/);
assert.match($.text(), /not a universal standard inclusion/);
assert.equal(faq.length, 3);
assert.deepEqual(comparisonPatch(revised), revised);
assert.throws(() => comparisonPatch({ content_html: '<iframe src="x"></iframe>' }), /additional media/);
const guide = { content_html: '<section id="model-answers"><p>Original answer</p><img src="a.jpg"></section>' };
const patch = guidePatch(guide);
assert.ok(patch.content_html.startsWith(guide.content_html));
assert.equal(load(patch.content_html)(`a[href="/compare/${comparisonSlug}"]`).length, 1);
assert.deepEqual(guidePatch(patch), {});
assert.throws(() => guidePatch({ content_html: '<section id="contessa-aeron-comparison"></section>' }), /Unexpected existing/);
console.log('PASS: evidence copy, sources, FAQ, image preservation, append-only guide link, idempotence and unsafe-media guard.');
